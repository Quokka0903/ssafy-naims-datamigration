-- =============================================================================
-- [NAIMS-2] DDL 컨벤션
-- 목적 : NAIMS-2 데이터베이스 스키마(테이블 DDL)의 명명·정렬 표준 기준 스크립트.
--        컬럼 한글 설명(메타데이터)은 별도 파일 "[NAIMS-2] DB 메타데이터 컨벤션.sql" 로 분리 관리.
--
-- [PK 명명 규칙]
--   * 모든 테이블에 명시적 PK 이름 부여 : CONSTRAINT [PK_<테이블명>] PRIMARY KEY CLUSTERED
--   * 익명 PK(시스템 자동 해시명) 금지 — DROP/스키마 비교 스크립트 안정성 확보.
--
-- [UNIQUE 명명 규칙]
--   * 고유 제약 : CONSTRAINT [UQ_<테이블명>_<컬럼>] UNIQUE  (예: UQ_OPERATOR_SETTING_REF)
--   * FILESTREAM 테이블 ROWGUID 는 UNIQUE NONCLUSTERED 로 보장.
--
-- [FK 명명 규칙]
--   * CONSTRAINT [FK_<자식약식>_<부모약식>] FOREIGN KEY(...) REFERENCES <부모>([RECORD_ID])
--   * 접두사 FK_ 로 통일(접미사 _FK 혼용 금지), WITH CHECK ADD + CHECK CONSTRAINT 2단 적용.
--   * 캐스케이드가 필요한 관계만 ON DELETE CASCADE 명시 (예: FK_VESSEL_DATA_COUNTRY).
--
-- [필드(컬럼) 정렬 규칙]
--   1) RECORD_ID (PK) 최상단
--   2) REF_*_ID (참조/외래 키)
--   3) 업무(도메인) 컬럼
--   4) 공통 메타 컬럼을 말미에 고정 순서로 : IS_TRAINING -> COMMENT -> (CREATED_DATETIME) -> CHNG_DATETIME -> DELETED
--   5) ROWGUID / FILESTREAM 부산물 컬럼은 최하단.
--
-- [인덱스 저장 옵션 — PK/UNIQUE 의 WITH(...) 절 의미]
--   PAD_INDEX = OFF                   : FILLFACTOR 여유 공간을 인덱스 중간(비-리프) 페이지에는 적용하지 않음.
--   STATISTICS_NORECOMPUTE = OFF      : 통계 자동 갱신 사용(끄지 않음) — 쿼리 실행계획 정확도 유지.
--   IGNORE_DUP_KEY = OFF              : 고유 인덱스에 중복 키 삽입 시 무시하지 않고 해당 INSERT 문 전체를 실패 처리.
--   ALLOW_ROW_LOCKS = ON              : 행(Row) 수준 잠금 허용 — 동시성 향상.
--   ALLOW_PAGE_LOCKS = ON             : 페이지(Page) 수준 잠금 허용.
--   FILLFACTOR = 80                   : 인덱스 리프 페이지를 80%까지만 채우고 20%를 여유로 남김 → 페이지 분할/단편화 감소.
--   OPTIMIZE_FOR_SEQUENTIAL_KEY = OFF : 순차 증가 키(IDENTITY 등) 말단 페이지 삽입 경합 최적화 기능 미사용.
--   ON [PRIMARY] / TEXTIMAGE_ON / FILESTREAM_ON : 인덱스·LOB·FILESTREAM 데이터의 저장 파일그룹 지정.
--   ※ 위 옵션값은 SSMS 스크립트 생성(Generate Scripts)의 표준 기본 구성이며, 별도 성능 튜닝값이 아니다.
--
-- 비고 : 본 파일은 컬럼 확장 속성(sys.sp_addextendedproperty)을 포함하지 않는다.
--        메타데이터는 "[NAIMS-2] DB 메타데이터 컨벤션.sql" 을 단일 출처로 한다.
-- =============================================================================

